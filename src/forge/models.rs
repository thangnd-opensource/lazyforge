/// A repository (GitHub) or project (GitLab), for the repository picker.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Repository {
    /// `group/project` or `owner/repo`.
    pub path: String,
    pub description: Option<String>,
    /// Last push or activity, for sorting and display.
    pub last_activity: Option<DateTime<Utc>>,
    pub web_url: String,
}

/// A branch of one repository, for the Branches view.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Branch {
    pub name: String,
    /// The repository's default branch (what other branches are compared with).
    pub default: bool,
    /// First line of the last commit's message.
    pub commit_title: String,
    pub commit_author: Option<String>,
    pub committed_at: Option<DateTime<Utc>>,
    /// Latest pipeline (GitLab) or combined checks (GitHub) of the last commit.
    pub pipeline_status: Option<PipelineStatus>,
    /// Number of an open merge/pull request from this branch, if there is one.
    pub merge_request: Option<u64>,
    pub web_url: String,
}

/// The branches of a repository, most recently updated first.
#[derive(Debug, Clone)]
pub struct BranchPage {
    pub default_branch: Option<String>,
    pub branches: Vec<Branch>,
}

/// The default branch first, then the most recently updated.
pub fn sort_branches(branches: &mut [Branch]) {
    branches.sort_by_key(|b| (!b.default, std::cmp::Reverse(b.committed_at)));
}

/// What `head` changed compared with `base`, counted from the commit where `head` left
/// `base` (like `git diff base...head`), so later changes on `base` do not show up.
#[derive(Debug, Clone)]
pub struct Comparison {
    pub base: String,
    pub head: String,
    /// Commits on `head` that `base` does not have.
    pub commits: usize,
    pub files: Vec<FileDiff>,
    pub web_url: String,
}

