/// Identifies a project in API calls: GitLab's numeric id (as text) or a GitHub
/// `owner/repo`.
pub type ProjectId = String;

/// Accepts a JSON number or string, for `ProjectId`s that GitLab sends as numbers.
fn number_or_string<'de, D: serde::Deserializer<'de>>(de: D) -> Result<String, D::Error> {
    #[derive(Deserialize)]
    #[serde(untagged)]
    enum NumberOrString {
        Number(u64),
        String(String),
    }
    Ok(match NumberOrString::deserialize(de)? {
        NumberOrString::Number(n) => n.to_string(),
        NumberOrString::String(s) => s,
    })
}

/// A CI pipeline (GitLab) or workflow run (GitHub).
#[derive(Debug, Clone, Deserialize)]
pub struct Pipeline {
    pub id: u64,
    /// Workflow name on GitHub; GitLab pipelines have none.
    #[serde(default)]
    pub name: Option<String>,
    /// The project the pipeline runs in. For merge requests from forks this is the fork,
    /// not the target project, so jobs and logs must be fetched from here.
    #[serde(deserialize_with = "number_or_string")]
    pub project_id: ProjectId,
    pub status: PipelineStatus,
    #[serde(rename = "ref")]
    pub git_ref: String,
    pub sha: String,
    pub source: Option<String>,
    pub created_at: DateTime<Utc>,
    pub updated_at: DateTime<Utc>,
    pub web_url: String,
}

/// A CI job. Job statuses use the same values as pipeline statuses.
#[derive(Debug, Clone, Deserialize)]
pub struct Job {
    pub id: u64,
    pub name: String,
    pub stage: String,
    pub status: PipelineStatus,
    pub created_at: DateTime<Utc>,
    pub started_at: Option<DateTime<Utc>>,
    pub finished_at: Option<DateTime<Utc>>,
    /// Seconds. `None` until the job has finished.
    pub duration: Option<f64>,
    #[serde(default)]
    pub allow_failure: bool,
    pub web_url: String,
}

/// The pipelines of a merge request, plus the jobs of one of them.
#[derive(Debug, Clone)]
pub struct CiSnapshot {
    /// Newest first.
    pub pipelines: Vec<Pipeline>,
    /// Which pipeline `jobs` belong to. `None` when there are no pipelines.
    pub pipeline_id: Option<u64>,
    /// Ordered by stage, then by creation within a stage.
    pub jobs: Vec<Job>,
}

/// Something the user can do to a pipeline or job.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum CiAction {
    RetryJob(u64),
    CancelJob(u64),
    /// Retries the failed and canceled jobs of the pipeline.
    RetryPipeline(u64),
    CancelPipeline(u64),
}

impl PipelineStatus {
    /// Still running or waiting to run, so it is worth polling.
    pub fn is_active(self) -> bool {
        matches!(
            self,
            Self::Created
                | Self::WaitingForResource
                | Self::WaitingForCallback
                | Self::Preparing
                | Self::Pending
                | Self::Running
                | Self::Canceling
        )
    }
}

/// Orders jobs like GitLab's pipeline view: stages in pipeline order, jobs by name within a
/// stage (so a retried job, which gets a new id, keeps its place). The jobs API does not
/// report stage order, but GitLab creates jobs stage by stage, so the smallest job id of
/// each stage gives the order.
pub fn sort_jobs(jobs: &mut [Job]) {
    let mut stage_rank = std::collections::HashMap::new();
    for job in jobs.iter() {
        let rank = stage_rank.entry(job.stage.clone()).or_insert(job.id);
        *rank = (*rank).min(job.id);
    }
    jobs.sort_by(|a, b| {
        (stage_rank[&a.stage], &a.name, a.id).cmp(&(stage_rank[&b.stage], &b.name, b.id))
    });
}

#[cfg(test)]
mod tests {
    use super::*;

    fn job(id: u64, stage: &str) -> Job {
        Job {
            id,
            name: format!("job{id}"),
            stage: stage.into(),
            status: PipelineStatus::Success,
            created_at: Utc::now(),
            started_at: None,
            finished_at: None,
            duration: None,
            allow_failure: false,
            web_url: String::new(),
        }
    }

    #[test]
    fn jobs_are_ordered_by_stage_then_name() {
        // As returned by the API: newest first. Job 12 is a retry of `job4` in "test", so it
        // has a newer id but keeps its place by name.
        let mut jobs = vec![
            job(12, "test"),
            job(9, "test"),
            job(7, "build"),
            job(5, "lint"),
            job(6, "build"),
        ];
        jobs[0].name = "job4".into();
        sort_jobs(&mut jobs);
        let order: Vec<_> = jobs
            .iter()
            .map(|j| (j.stage.as_str(), j.name.as_str()))
            .collect();
        assert_eq!(
            order,
            vec![
                ("lint", "job5"),
                ("build", "job6"),
                ("build", "job7"),
                ("test", "job4"),
                ("test", "job9")
            ]
        );
    }

    #[test]
    fn parses_a_real_job() {
        // Trimmed from `GET /projects/:id/pipelines/:id/jobs` on gitlab.com.
        let json = r#"{"id": 17078087917, "name": "govulncheck", "stage": "application-security-testing",
            "status": "manual", "created_at": "2026-10-10T07:04:56.400Z", "started_at": null,
            "finished_at": null, "duration": null, "queued_duration": null, "allow_failure": true,
            "web_url": "https://gitlab.com/x/-/jobs/17078087917", "tag_list": [], "runner": null}"#;
        let job: Job = serde_json::from_str(json).unwrap();
        assert_eq!(job.status, PipelineStatus::Manual);
        assert!(job.allow_failure);
        assert!(!job.status.is_active());
    }

    #[test]
    fn pipeline_status_accepts_rest_and_graphql_spelling() {
        let rest: PipelineStatus = serde_json::from_str(r#""waiting_for_resource""#).unwrap();
        let graphql: PipelineStatus = serde_json::from_str(r#""WAITING_FOR_RESOURCE""#).unwrap();
        assert_eq!(rest, PipelineStatus::WaitingForResource);
        assert_eq!(graphql, PipelineStatus::WaitingForResource);
        let new: PipelineStatus = serde_json::from_str(r#""brand_new""#).unwrap();
        assert_eq!(new, PipelineStatus::Unknown);
    }
}
